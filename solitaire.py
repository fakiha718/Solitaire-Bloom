"""
solitaire.py - Core Klondike Solitaire Game Engine
=================================================

Academic Data Structures & Algorithms Implementation
Orchestrates Klondike Solitaire rules, move validation, game state metadata,
dual-stack Undo/Redo mechanisms, scoring, timers, and the strategic hint engine.
"""

import random
import time
from typing import Optional, List, Dict, Tuple, Any

from card import Card, Suit, Rank
from data_structures import Node, Stack, Queue, DoublyLinkedList


class MoveType:
    """Enumeration of move types for Command Pattern tracking."""
    DRAW = "DRAW"
    RECYCLE = "RECYCLE"
    WASTE_TO_TABLEAU = "WASTE_TO_TABLEAU"
    WASTE_TO_FOUNDATION = "WASTE_TO_FOUNDATION"
    TABLEAU_TO_FOUNDATION = "TABLEAU_TO_FOUNDATION"
    TABLEAU_TO_TABLEAU = "TABLEAU_TO_TABLEAU"
    FOUNDATION_TO_TABLEAU = "FOUNDATION_TO_TABLEAU"


class MoveRecord:
    """
    Encapsulates all metadata required to execute, reverse (undo), or replay (redo) a move.
    """

    def __init__(
        self,
        move_type: str,
        src: str,
        dst: str,
        card_count: int = 1,
        cards: Optional[List[Card]] = None,
        flipped_card: Optional[Card] = None,
        score_delta: int = 0,
    ):
        self.move_type: str = move_type
        self.src: str = src
        self.dst: str = dst
        self.card_count: int = card_count
        self.cards: List[Card] = cards or []
        self.flipped_card: Optional[Card] = flipped_card
        self.score_delta: int = score_delta

    def __repr__(self) -> str:
        return (
            f"MoveRecord({self.move_type}, src={self.src}, dst={self.dst}, "
            f"count={self.card_count}, score={self.score_delta})"
        )


class Hint:
    """Represents a recommended legal move generated by the Hint engine."""

    def __init__(self, description: str, priority: int, command_suggestion: str):
        self.description: str = description
        self.priority: int = priority  # 1 = Highest
        self.command_suggestion: str = command_suggestion

    def __repr__(self) -> str:
        return f"Hint(P{self.priority}: {self.description} -> [{self.command_suggestion}])"


class KlondikeSolitaire:
    """
    Klondike Solitaire Game Engine strictly adhering to academic DSA specifications.

    Core Data Structures Utilized:
        - Array (Python List): Initial 52-card deck generation, indexing, and shuffling.
        - Queue (FIFO): Stockpile draw pile.
        - Stack (LIFO): Waste pile and the 4 Foundation piles.
        - DoublyLinkedList: The 7 Tableau columns supporting O(1) slice and splice.
        - Stack (LIFO): Dual stacks for Undo and Redo command histories.
        - HashMap (Dictionary): Metadata registry of card states and pile references.
    """

    def __init__(self, seed: Optional[int] = None) -> None:
        self.seed: Optional[int] = seed

        # Game State Piles
        self.stock: Queue[Card] = Queue[Card]()
        self.waste: Stack[Card] = Stack[Card]()
        self.foundations: Dict[str, Stack[Card]] = {
            Suit.HEARTS: Stack[Card](),
            Suit.DIAMONDS: Stack[Card](),
            Suit.CLUBS: Stack[Card](),
            Suit.SPADES: Stack[Card](),
        }
        self.tableaux: List[DoublyLinkedList[Card]] = [
            DoublyLinkedList[Card]() for _ in range(7)
        ]

        # Dual Stacks for Undo and Redo History
        self.undo_stack: Stack[MoveRecord] = Stack[MoveRecord]()
        self.redo_stack: Stack[MoveRecord] = Stack[MoveRecord]()

        # HashMap / Dictionary for Game State Metadata and Quick Lookups
        self.piles: Dict[str, Any] = {}
        self.card_registry: Dict[str, Dict[str, Any]] = {}

        # Game Metrics
        self.moves_count: int = 0
        self.score: int = 0
        self.start_time: float = time.time()
        self.is_game_won: bool = False

        # Initialize and deal deck
        self.start_new_game(seed=seed)

    def _build_deck(self) -> List[Card]:
        """
        Generates a standard 52-card deck stored in a Python list (Array).
        Complexity: O(52) = O(1)
        """
        deck: List[Card] = []
        for suit in [Suit.HEARTS, Suit.DIAMONDS, Suit.CLUBS, Suit.SPADES]:
            for rank in range(1, 14):
                deck.append(Card(suit=suit, rank=rank, is_face_up=False))
        return deck

    def start_new_game(self, seed: Optional[int] = None) -> None:
        """
        Initializes a fresh game:
        1. Empties all piles.
        2. Generates and shuffles the 52-card array.
        3. Deals cards to the 7 Tableau columns (1 to 7 cards, exposed tail face-up).
        4. Enqueues the remaining 24 cards into the Stockpile Queue.
        5. Updates metadata registries and resets metrics.
        """
        if seed is not None:
            self.seed = seed
            random.seed(self.seed)

        # Clear existing piles
        self.stock.clear()
        self.waste.clear()
        for f in self.foundations.values():
            f.clear()
        for t in self.tableaux:
            t.clear()

        self.undo_stack.clear()
        self.redo_stack.clear()
        self.moves_count = 0
        self.score = 0
        self.start_time = time.time()
        self.is_game_won = False

        # 1. Deck generation & shuffling (Array / List)
        deck: List[Card] = self._build_deck()
        random.shuffle(deck)

        # 2. Deal to the 7 Tableau DoublyLinkedLists
        # Column i (0 to 6) receives i + 1 cards
        deck_idx = 0
        for col in range(7):
            num_cards = col + 1
            for i in range(num_cards):
                card = deck[deck_idx]
                deck_idx += 1
                # Only the bottom (tail) card is initially face-up
                card.is_face_up = (i == num_cards - 1)
                self.tableaux[col].append(card)

        # 3. Enqueue remaining 24 cards to Stockpile Queue
        while deck_idx < 52:
            card = deck[deck_idx]
            deck_idx += 1
            card.is_face_up = False
            self.stock.enqueue(card)

        # 4. Initialize Metadata HashMap
        self._init_metadata()

    def _init_metadata(self) -> None:
        """
        Populates Dictionary / HashMap mappings for quick pile lookups and card state metadata.
        """
        self.piles = {
            "stock": self.stock,
            "waste": self.waste,
            "foundation_H": self.foundations[Suit.HEARTS],
            "foundation_D": self.foundations[Suit.DIAMONDS],
            "foundation_C": self.foundations[Suit.CLUBS],
            "foundation_S": self.foundations[Suit.SPADES],
        }
        for i, t in enumerate(self.tableaux):
            self.piles[f"tableau_{i}"] = t

        # Card registry mapping card_id -> state dictionary
        self.card_registry.clear()
        self._refresh_card_registry()

    def _refresh_card_registry(self) -> None:
        """Updates the card registry with current locations and states."""
        # Stock
        for c in self.stock:
            self.card_registry[c.id] = {
                "card": c, "pile": "stock", "is_face_up": c.is_face_up
            }
        # Waste
        for c in self.waste:
            self.card_registry[c.id] = {
                "card": c, "pile": "waste", "is_face_up": c.is_face_up
            }
        # Foundations
        for suit, f in self.foundations.items():
            short_s = Suit.SHORT_CODES[suit]
            for c in f:
                self.card_registry[c.id] = {
                    "card": c, "pile": f"foundation_{short_s}", "is_face_up": c.is_face_up
                }
        # Tableaux
        for col_idx, t in enumerate(self.tableaux):
            for c in t:
                self.card_registry[c.id] = {
                    "card": c, "pile": f"tableau_{col_idx}", "is_face_up": c.is_face_up
                }

    # =====================================================================
    # Core Game Mechanics
    # =====================================================================

    def draw(self) -> Tuple[bool, str]:
        """
        Draws one card from the Stockpile Queue to the Waste Stack.
        If Stock is empty, recycles all cards from Waste back into Stock.
        """
        if not self.stock.is_empty():
            # Draw card: FIFO dequeue from stock, push face-up to waste Stack
            card = self.stock.dequeue()
            card.is_face_up = True
            self.waste.push(card)

            move = MoveRecord(
                move_type=MoveType.DRAW,
                src="stock",
                dst="waste",
                cards=[card],
                score_delta=0,
            )
            self._commit_move(move)
            return True, f"Drew {card.display()} from Stock to Waste."
        else:
            # Stock empty: Recycle Waste into Stock
            if self.waste.is_empty():
                return False, "Stock and Waste are both empty. Cannot draw or recycle."

            recycled_cards: List[Card] = []
            while not self.waste.is_empty():
                card = self.waste.pop()
                card.is_face_up = False
                self.stock.enqueue(card)
                recycled_cards.append(card)

            # Score penalty for recycling (Klondike rule: -20, floor at 0)
            score_delta = -20 if self.score >= 20 else -self.score

            move = MoveRecord(
                move_type=MoveType.RECYCLE,
                src="waste",
                dst="stock",
                cards=recycled_cards,
                score_delta=score_delta,
            )
            self._commit_move(move)
            return True, f"Recycled {len(recycled_cards)} cards from Waste back to Stock."

    def waste_to_tableau(self, col_idx: int) -> Tuple[bool, str]:
        """
        Moves the top card of the Waste Stack onto Tableau column `col_idx` (0-6).
        """
        if not (0 <= col_idx < 7):
            return False, f"Invalid tableau column index: {col_idx + 1}. Must be 1 to 7."

        if self.waste.is_empty():
            return False, "Waste pile is empty."

        target_col = self.tableaux[col_idx]
        card = self.waste.peek()
        assert card is not None

        # Validate Tableau stacking rules
        target_tail = target_col.peek_tail()
        if not card.can_stack_on_tableau(target_tail):
            if target_tail is None:
                return False, f"Only a King (rank 13) can occupy an empty tableau column. ({card.id} is rank {card.rank})"
            return False, f"Cannot place {card.id} ({card.color}) on {target_tail.id} ({target_tail.color})."

        # Execute move
        popped_card = self.waste.pop()
        target_col.append(popped_card)

        score_delta = 5  # Standard score for Waste -> Tableau
        move = MoveRecord(
            move_type=MoveType.WASTE_TO_TABLEAU,
            src="waste",
            dst=f"tableau_{col_idx}",
            cards=[popped_card],
            score_delta=score_delta,
        )
        self._commit_move(move)
        return True, f"Moved {popped_card.display()} from Waste to Tableau {col_idx + 1}."

    def waste_to_foundation(self) -> Tuple[bool, str]:
        """
        Moves the top card of the Waste Stack to its corresponding Foundation pile.
        """
        if self.waste.is_empty():
            return False, "Waste pile is empty."

        card = self.waste.peek()
        assert card is not None
        foundation = self.foundations[card.suit]
        foundation_top = foundation.peek()

        if not card.can_stack_on_foundation(foundation_top):
            if foundation_top is None:
                return False, f"Cannot place {card.id} on empty foundation; only an Ace can start a foundation."
            return False, f"Cannot place {card.id} on {foundation_top.id} ({card.suit} requires rank {foundation_top.rank + 1})."

        # Execute move
        popped_card = self.waste.pop()
        foundation.push(popped_card)

        score_delta = 10  # Standard score for Waste -> Foundation
        move = MoveRecord(
            move_type=MoveType.WASTE_TO_FOUNDATION,
            src="waste",
            dst=f"foundation_{Suit.SHORT_CODES[card.suit]}",
            cards=[popped_card],
            score_delta=score_delta,
        )
        self._commit_move(move)
        self._check_win_condition()
        return True, f"Moved {popped_card.display()} to Foundation {Suit.SYMBOLS[card.suit]}."

    def tableau_to_foundation(self, col_idx: int) -> Tuple[bool, str]:
        """
        Moves the exposed tail card of Tableau column `col_idx` (0-6) to its matching Foundation.
        If a face-down card is exposed on the column, it is flipped face-up.
        """
        if not (0 <= col_idx < 7):
            return False, f"Invalid tableau column index: {col_idx + 1}. Must be 1 to 7."

        col = self.tableaux[col_idx]
        if col.is_empty():
            return False, f"Tableau column {col_idx + 1} is empty."

        card = col.peek_tail()
        assert card is not None
        if not card.is_face_up:
            return False, "Cannot move a face-down card."

        foundation = self.foundations[card.suit]
        foundation_top = foundation.peek()

        if not card.can_stack_on_foundation(foundation_top):
            if foundation_top is None:
                return False, f"Cannot place {card.id} on empty foundation; only an Ace can start a foundation."
            return False, f"Cannot place {card.id} on {foundation_top.id} ({card.suit} requires rank {foundation_top.rank + 1})."

        # Pop from tableau
        popped_card = col.pop_tail()
        foundation.push(popped_card)

        score_delta = 10  # Tableau -> Foundation

        # Card reveal logic: Flip newly exposed tail if face-down
        flipped_card: Optional[Card] = None
        new_tail = col.peek_tail()
        if new_tail is not None and not new_tail.is_face_up:
            new_tail.flip()
            flipped_card = new_tail
            score_delta += 5  # Bonus for revealing card

        move = MoveRecord(
            move_type=MoveType.TABLEAU_TO_FOUNDATION,
            src=f"tableau_{col_idx}",
            dst=f"foundation_{Suit.SHORT_CODES[popped_card.suit]}",
            cards=[popped_card],
            flipped_card=flipped_card,
            score_delta=score_delta,
        )
        self._commit_move(move)
        self._check_win_condition()
        msg = f"Moved {popped_card.display()} from Tableau {col_idx + 1} to Foundation {Suit.SYMBOLS[popped_card.suit]}."
        if flipped_card:
            msg += f" Revealed {flipped_card.display()}."
        return True, msg

    def tableau_to_tableau(
        self, src_col_idx: int, card_or_index_or_code: Any, dst_col_idx: int
    ) -> Tuple[bool, str]:
        """
        Moves a sublist of cards from `src_col_idx` to `dst_col_idx`.
        Uses custom DoublyLinkedList.split_sublist() and DoublyLinkedList.splice()
        for true academic O(1) pointer-based concatenation.

        Parameters:
            src_col_idx: Source column index (0-6).
            card_or_index_or_code:
                - Card instance, OR
                - String card code (e.g., '10H', 'S-K', 'A♦'), OR
                - Integer count of cards from tail (1 = tail card, 2 = 2 cards, etc.).
            dst_col_idx: Destination column index (0-6).
        """
        if not (0 <= src_col_idx < 7) or not (0 <= dst_col_idx < 7):
            return False, "Column indices must be between 1 and 7."
        if src_col_idx == dst_col_idx:
            return False, "Source and destination columns cannot be the same."

        src_col = self.tableaux[src_col_idx]
        dst_col = self.tableaux[dst_col_idx]

        if src_col.is_empty():
            return False, f"Source column {src_col_idx + 1} is empty."

        # Locate the starting Node for slicing
        start_node = self._resolve_tableau_node(src_col, card_or_index_or_code)
        if start_node is None:
            return False, f"Could not find valid card matching '{card_or_index_or_code}' in Tableau {src_col_idx + 1}."

        lead_card: Card = start_node.data
        if not lead_card.is_face_up:
            return False, f"Cannot move face-down card: {lead_card}."

        # Validate placement on destination column
        dst_tail = dst_col.peek_tail()
        if not lead_card.can_stack_on_tableau(dst_tail):
            if dst_tail is None:
                return False, f"Only a King can be moved to an empty column. ({lead_card.id} is rank {lead_card.rank})"
            return False, f"Cannot place {lead_card.id} ({lead_card.color}) on {dst_tail.id} ({dst_tail.color})."

        # Count cards being sliced
        cards_moving: List[Card] = []
        curr: Optional[Node[Card]] = start_node
        while curr is not None:
            cards_moving.append(curr.data)
            curr = curr.next

        # Execute Slice and Splice
        sublist = src_col.split_sublist(start_node)
        dst_col.splice(sublist)

        score_delta = 0
        flipped_card: Optional[Card] = None
        new_src_tail = src_col.peek_tail()
        if new_src_tail is not None and not new_src_tail.is_face_up:
            new_src_tail.flip()
            flipped_card = new_src_tail
            score_delta += 5  # Bonus for revealing card

        move = MoveRecord(
            move_type=MoveType.TABLEAU_TO_TABLEAU,
            src=f"tableau_{src_col_idx}",
            dst=f"tableau_{dst_col_idx}",
            card_count=len(cards_moving),
            cards=cards_moving,
            flipped_card=flipped_card,
            score_delta=score_delta,
        )
        self._commit_move(move)

        msg = (
            f"Moved {len(cards_moving)} card(s) (starting with {lead_card.display()}) "
            f"from Tableau {src_col_idx + 1} to Tableau {dst_col_idx + 1}."
        )
        if flipped_card:
            msg += f" Revealed {flipped_card.display()}."
        return True, msg

    def foundation_to_tableau(self, suit_name: str, dst_col_idx: int) -> Tuple[bool, str]:
        """
        Moves the top card of a Foundation pile back down to Tableau column `dst_col_idx`.
        Standard Solitaire rule; useful for unblocking columns.
        """
        if not (0 <= dst_col_idx < 7):
            return False, f"Invalid tableau column index: {dst_col_idx + 1}."

        # Resolve suit
        resolved_suit = None
        for s in [Suit.HEARTS, Suit.DIAMONDS, Suit.CLUBS, Suit.SPADES]:
            if (
                suit_name.upper() == s.upper()
                or suit_name.upper() == Suit.SHORT_CODES[s]
                or suit_name == Suit.SYMBOLS[s]
            ):
                resolved_suit = s
                break
        if resolved_suit is None:
            return False, f"Unknown suit identifier: '{suit_name}'."

        foundation = self.foundations[resolved_suit]
        if foundation.is_empty():
            return False, f"Foundation {Suit.SYMBOLS[resolved_suit]} is empty."

        card = foundation.peek()
        assert card is not None
        dst_col = self.tableaux[dst_col_idx]
        dst_tail = dst_col.peek_tail()

        if not card.can_stack_on_tableau(dst_tail):
            if dst_tail is None:
                return False, f"Only a King can be moved to an empty column."
            return False, f"Cannot place {card.id} on {dst_tail.id}."

        # Execute move
        popped_card = foundation.pop()
        dst_col.append(popped_card)

        score_delta = -15  # Penalty for moving card off foundation
        move = MoveRecord(
            move_type=MoveType.FOUNDATION_TO_TABLEAU,
            src=f"foundation_{Suit.SHORT_CODES[resolved_suit]}",
            dst=f"tableau_{dst_col_idx}",
            cards=[popped_card],
            score_delta=score_delta,
        )
        self._commit_move(move)
        return True, f"Moved {popped_card.display()} from Foundation to Tableau {dst_col_idx + 1}."

    # =====================================================================
    # Node Lookup Helper for Tableaux
    # =====================================================================

    def _resolve_tableau_node(
        self, col: DoublyLinkedList[Card], card_or_index_or_code: Any
    ) -> Optional[Node[Card]]:
        """
        Academic pointer resolution: finds the Node inside a Tableau DoublyLinkedList
        by either Card object, card ID, shorthand (e.g. '10H'), or tail offset count.
        """
        if isinstance(card_or_index_or_code, Node):
            return card_or_index_or_code

        if isinstance(card_or_index_or_code, Card):
            return col.find_node(card_or_index_or_code)

        # If integer: count of cards from tail (1 = tail, 2 = tail - 1, etc.)
        if isinstance(card_or_index_or_code, int):
            count = card_or_index_or_code
            if count <= 0 or count > col.size():
                return None
            target_idx = col.size() - count
            return col.get_node_at(target_idx)

        # If string: normalize and match card ID or rank/suit representation
        query = str(card_or_index_or_code).strip().upper()
        # Check if query is integer string
        if query.isdigit():
            count = int(query)
            if count <= 0 or count > col.size():
                return None
            return col.get_node_at(col.size() - count)

        # Check by ID or display string
        curr = col.head
        while curr is not None:
            c = curr.data
            if c.is_face_up:
                norm_id = c.id.replace("-", "").upper()
                norm_full = f"{c.rank_str}{c.short_suit}".upper()
                norm_symbol = f"{c.rank_str}{c.symbol}".upper()
                q_clean = query.replace("-", "")
                if (
                    q_clean == norm_id
                    or q_clean == norm_full
                    or query == norm_symbol
                    or query == c.id.upper()
                ):
                    return curr
            curr = curr.next

        return None

    # =====================================================================
    # Undo & Redo System (Dual LIFO Stacks)
    # =====================================================================

    def _commit_move(self, move: MoveRecord) -> None:
        """
        Commits a newly executed move: pushes to undo stack, clears redo stack,
        increments move counter, adjusts score, and refreshes metadata.
        """
        self.undo_stack.push(move)
        self.redo_stack.clear()
        self.moves_count += 1
        self.score = max(0, self.score + move.score_delta)
        self._refresh_card_registry()

    def undo(self) -> Tuple[bool, str]:
        """
        Reverses the last action using the LIFO Undo Stack.
        Pushes the reversed move to the Redo Stack.
        """
        if self.undo_stack.is_empty():
            return False, "Nothing to undo."

        move = self.undo_stack.pop()

        if move.move_type == MoveType.DRAW:
            # Reverse DRAW: Pop card from waste, flip face-down, prepend back to stock queue
            card = self.waste.pop()
            card.is_face_up = False
            self.stock.prepend(card)

        elif move.move_type == MoveType.RECYCLE:
            # Reverse RECYCLE: Drain stock, push cards back onto waste stack face-up
            # In reverse order of move.cards to preserve exact original stack state
            num_cards = len(move.cards)
            for _ in range(num_cards):
                self.stock.dequeue()
            for c in reversed(move.cards):
                c.is_face_up = True
                self.waste.push(c)

        elif move.move_type == MoveType.WASTE_TO_TABLEAU:
            col_idx = int(move.dst.split("_")[1])
            card = self.tableaux[col_idx].pop_tail()
            self.waste.push(card)

        elif move.move_type == MoveType.WASTE_TO_FOUNDATION:
            short_s = move.dst.split("_")[1]
            suit = Suit.SHORT_TO_SUIT[short_s]
            card = self.foundations[suit].pop()
            self.waste.push(card)

        elif move.move_type == MoveType.TABLEAU_TO_FOUNDATION:
            col_idx = int(move.src.split("_")[1])
            short_s = move.dst.split("_")[1]
            suit = Suit.SHORT_TO_SUIT[short_s]
            card = self.foundations[suit].pop()

            # If a card was exposed and flipped during this move, unflip it
            if move.flipped_card:
                move.flipped_card.is_face_up = False

            self.tableaux[col_idx].append(card)

        elif move.move_type == MoveType.TABLEAU_TO_TABLEAU:
            src_col_idx = int(move.src.split("_")[1])
            dst_col_idx = int(move.dst.split("_")[1])
            src_col = self.tableaux[src_col_idx]
            dst_col = self.tableaux[dst_col_idx]

            # Unflip source exposed card if applicable
            if move.flipped_card:
                move.flipped_card.is_face_up = False

            # Slice the spliced segment from dst_col and splice back to src_col
            # Sliced segment starts at (dst_col.size() - move.card_count)
            split_idx = dst_col.size() - move.card_count
            start_node = dst_col.get_node_at(split_idx)
            assert start_node is not None
            sublist = dst_col.split_sublist(start_node)
            src_col.splice(sublist)

        elif move.move_type == MoveType.FOUNDATION_TO_TABLEAU:
            short_s = move.src.split("_")[1]
            suit = Suit.SHORT_TO_SUIT[short_s]
            col_idx = int(move.dst.split("_")[1])
            card = self.tableaux[col_idx].pop_tail()
            self.foundations[suit].push(card)

        # Update metrics
        self.score = max(0, self.score - move.score_delta)
        self.moves_count += 1
        self.redo_stack.push(move)
        self._refresh_card_registry()
        self.is_game_won = False
        return True, f"Undid {move.move_type}."

    def redo(self) -> Tuple[bool, str]:
        """
        Replays the last undone move using the LIFO Redo Stack.
        Pushes back to the Undo Stack.
        """
        if self.redo_stack.is_empty():
            return False, "Nothing to redo."

        move = self.redo_stack.pop()

        if move.move_type == MoveType.DRAW:
            card = self.stock.dequeue()
            card.is_face_up = True
            self.waste.push(card)

        elif move.move_type == MoveType.RECYCLE:
            while not self.waste.is_empty():
                c = self.waste.pop()
                c.is_face_up = False
                self.stock.enqueue(c)

        elif move.move_type == MoveType.WASTE_TO_TABLEAU:
            col_idx = int(move.dst.split("_")[1])
            card = self.waste.pop()
            self.tableaux[col_idx].append(card)

        elif move.move_type == MoveType.WASTE_TO_FOUNDATION:
            short_s = move.dst.split("_")[1]
            suit = Suit.SHORT_TO_SUIT[short_s]
            card = self.waste.pop()
            self.foundations[suit].push(card)

        elif move.move_type == MoveType.TABLEAU_TO_FOUNDATION:
            col_idx = int(move.src.split("_")[1])
            short_s = move.dst.split("_")[1]
            suit = Suit.SHORT_TO_SUIT[short_s]
            card = self.tableaux[col_idx].pop_tail()
            if move.flipped_card:
                move.flipped_card.is_face_up = True
            self.foundations[suit].push(card)

        elif move.move_type == MoveType.TABLEAU_TO_TABLEAU:
            src_col_idx = int(move.src.split("_")[1])
            dst_col_idx = int(move.dst.split("_")[1])
            src_col = self.tableaux[src_col_idx]
            dst_col = self.tableaux[dst_col_idx]

            split_idx = src_col.size() - move.card_count
            start_node = src_col.get_node_at(split_idx)
            assert start_node is not None
            sublist = src_col.split_sublist(start_node)
            dst_col.splice(sublist)
            if move.flipped_card:
                move.flipped_card.is_face_up = True

        elif move.move_type == MoveType.FOUNDATION_TO_TABLEAU:
            short_s = move.src.split("_")[1]
            suit = Suit.SHORT_TO_SUIT[short_s]
            col_idx = int(move.dst.split("_")[1])
            card = self.foundations[suit].pop()
            self.tableaux[col_idx].append(card)

        # Update metrics
        self.score = max(0, self.score + move.score_delta)
        self.moves_count += 1
        self.undo_stack.push(move)
        self._refresh_card_registry()
        self._check_win_condition()
        return True, f"Redid {move.move_type}."

    # =====================================================================
    # Victory Condition & Metrics
    # =====================================================================

    def _check_win_condition(self) -> bool:
        """
        Evaluates win condition: All 4 foundation piles contain 13 cards (total 52).
        """
        total_foundation_cards = sum(f.size() for f in self.foundations.values())
        if total_foundation_cards == 52:
            self.is_game_won = True
            return True
        return False

    def get_elapsed_seconds(self) -> int:
        """Returns elapsed game duration in integer seconds."""
        return int(time.time() - self.start_time)

    def get_formatted_time(self) -> str:
        """Returns elapsed time in 'MM:SS' format."""
        secs = self.get_elapsed_seconds()
        mins = secs // 60
        s = secs % 60
        return f"{mins:02d}:{s:02d}"

    # =====================================================================
    # Strategic Hint System
    # =====================================================================

    def get_hints(self) -> List[Hint]:
        """
        Evaluates the board state and returns a prioritized list of legal moves.

        Priority Order:
            1. Safe / high-value moves to Foundation (Aces and Twos, or unblocking).
            2. Any Tableau tail card to Foundation.
            3. Waste card to Foundation.
            4. Tableau-to-Tableau moves that uncover a face-down card.
            5. Waste card to Tableau that advances play.
            6. Moving a King to an empty tableau column (if uncovering hidden cards).
            7. Other Tableau-to-Tableau moves.
            8. Draw from Stock (or recycle if stock is empty).
        """
        hints: List[Hint] = []

        # 1 & 2: Tableau to Foundation
        for col_idx, col in enumerate(self.tableaux):
            tail = col.peek_tail()
            if tail is not None and tail.is_face_up:
                foundation = self.foundations[tail.suit]
                f_top = foundation.peek()
                if tail.can_stack_on_foundation(f_top):
                    priority = 1 if tail.rank <= 2 else 2
                    hints.append(
                        Hint(
                            description=f"Move {tail.id} from Tableau {col_idx + 1} to Foundation {Suit.SYMBOLS[tail.suit]}",
                            priority=priority,
                            command_suggestion=f"tf {col_idx + 1}",
                        )
                    )

        # 3: Waste to Foundation
        if not self.waste.is_empty():
            w_card = self.waste.peek()
            assert w_card is not None
            foundation = self.foundations[w_card.suit]
            f_top = foundation.peek()
            if w_card.can_stack_on_foundation(f_top):
                priority = 1 if w_card.rank <= 2 else 3
                hints.append(
                    Hint(
                        description=f"Move {w_card.id} from Waste to Foundation {Suit.SYMBOLS[w_card.suit]}",
                        priority=priority,
                        command_suggestion="wf",
                    )
                )

        # 4 & 6 & 7: Tableau to Tableau moves
        for src_idx, src_col in enumerate(self.tableaux):
            if src_col.is_empty():
                continue

            # Iterate through all face-up cards in src_col
            curr = src_col.head
            has_hidden_underneath = False
            while curr is not None:
                if not curr.data.is_face_up:
                    has_hidden_underneath = True
                else:
                    card = curr.data
                    # Test moving this sublist onto all other columns
                    for dst_idx, dst_col in enumerate(self.tableaux):
                        if dst_idx == src_idx:
                            continue
                        dst_tail = dst_col.peek_tail()
                        if card.can_stack_on_tableau(dst_tail):
                            # Evaluate move strategic value
                            if dst_tail is None:
                                # Moving King to empty column
                                if curr is src_col.head and not has_hidden_underneath:
                                    # Don't suggest moving King from one empty base to another empty base
                                    continue
                                priority = 4 if has_hidden_underneath else 6
                                desc = f"Move King {card.id} run from Col {src_idx + 1} to empty Col {dst_idx + 1}"
                            elif has_hidden_underneath and curr.prev and not curr.prev.data.is_face_up:
                                priority = 4  # High priority: uncovers hidden card!
                                desc = f"Move {card.id} run from Col {src_idx + 1} to Col {dst_idx + 1} to reveal a hidden card"
                            else:
                                priority = 7
                                desc = f"Move {card.id} run from Col {src_idx + 1} onto {dst_tail.id} (Col {dst_idx + 1})"

                            hints.append(
                                Hint(
                                    description=desc,
                                    priority=priority,
                                    command_suggestion=f"m {src_idx + 1} {dst_idx + 1} {card.id}",
                                )
                            )
                curr = curr.next

        # 5: Waste to Tableau
        if not self.waste.is_empty():
            w_card = self.waste.peek()
            assert w_card is not None
            for dst_idx, dst_col in enumerate(self.tableaux):
                dst_tail = dst_col.peek_tail()
                if w_card.can_stack_on_tableau(dst_tail):
                    priority = 5 if dst_tail is not None else 6
                    target_name = dst_tail.id if dst_tail else "empty column"
                    hints.append(
                        Hint(
                            description=f"Move {w_card.id} from Waste onto {target_name} (Col {dst_idx + 1})",
                            priority=priority,
                            command_suggestion=f"wt {dst_idx + 1}",
                        )
                    )

        # 8: Draw / Recycle
        if not self.stock.is_empty():
            hints.append(
                Hint(
                    description="Draw the next card from Stock",
                    priority=8,
                    command_suggestion="d",
                )
            )
        elif not self.waste.is_empty():
            hints.append(
                Hint(
                    description="Recycle Waste back into Stock",
                    priority=9,
                    command_suggestion="d",
                )
            )

        # Sort hints by priority (ascending: 1 first)
        hints.sort(key=lambda h: h.priority)
        return hints

    # =====================================================================
    # Auto-Complete Safe Foundation Moves
    # =====================================================================

    def auto_step_foundation(self) -> Tuple[bool, str]:
        """
        Executes one safe/obvious foundation move if available (Tableau or Waste to Foundation).
        Returns True and description if a move was executed, False otherwise.
        """
        # Check Tableau tail cards
        for col_idx, col in enumerate(self.tableaux):
            tail = col.peek_tail()
            if tail is not None and tail.is_face_up:
                foundation = self.foundations[tail.suit]
                if tail.can_stack_on_foundation(foundation.peek()):
                    success, msg = self.tableau_to_foundation(col_idx)
                    if success:
                        return True, msg

        # Check Waste card
        if not self.waste.is_empty():
            w_card = self.waste.peek()
            assert w_card is not None
            foundation = self.foundations[w_card.suit]
            if w_card.can_stack_on_foundation(foundation.peek()):
                success, msg = self.waste_to_foundation()
                if success:
                    return True, msg

        return False, "No automated foundation moves available."
